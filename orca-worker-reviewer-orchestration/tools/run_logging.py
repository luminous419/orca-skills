# The algorithm travels with the value, so a future algorithm change is a visible
# reinterpretation rather than a silent one.


def sha256_text(text: str) -> str:
    """sha256 of the exact string, UTF-8 encoded, with NO normalization."""
    return "sha256:" + hashlib.sha256(text.encode("utf-8")).hexdigest()


def sha256_bytes(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data).hexdigest()


# ---- redaction policy v1.1 -------------------------------------------------------
# Order is part of the policy, not an implementation detail: a dcap_ token inside an
# environment assignment is redacted and counted by orca_dispatch_capability, not by
# env_secret_pattern, because the first pass has already replaced it. Declaring the
# order is what makes the counts reproducible.
#
# v1.1 adds category 5. v1.0 stated the absolute-path rule as an ALLOWLIST of three
# dangerous roots, which fails open on every root nobody thought of -- a real retained
# baseline carried /private/tmp/claude-<uid>/-Users-<user>-.../<session-uuid>/... through
# untouched while the record truthfully reported zero redactions. v1.1 inverts the
# posture: category 4 keeps its narrow, readability-preserving job for the three home
# spellings, and category 5 catches every OTHER absolute path by default, with NO
# minimum segment count -- '/luminous', '/workspace-501' and '/session-<uuid>' are each
# one segment and each identifies a user, a uid-derived workspace or a session, so a
# segment-count carve-out would be the same fail-open shape one level down.

# A path-segment character. Excludes the separator, whitespace, the quoting/bracketing
# punctuation a path is normally embedded in, and the angle brackets a placeholder
# uses, so a match stops at prose punctuation and never swallows a <PLACEHOLDER>.
_PATH_SEGMENT = r"[^/\s\"'`,;:<>|)\]}]+"

# Category 4 -- home-rooted. UNCHANGED from redaction/1.0. Replaces the user-name
# segment only, so the remainder of the path stays semantically readable.
_HOME_ABSOLUTE_PATH = re.compile(r"(/Users/|/home/|/root/)(?!<|\{)[^/\s\"'`,;:)\]}]+")

# Category 5 -- NEW in redaction/1.1. Every absolute POSIX path category 4 does not
# already own, with NO minimum segment count. Replaces the ENTIRE match.
_FOREIGN_ABSOLUTE_PATH = re.compile(
    r"(?:(?<=file://)|(?<![\w>/]))"    # left boundary: start-of-text, or a delimiter
                                      #   that is not a word char, not '>' (so
                                      #   `<ROOT>/a/b` survives) and not '/' (so
                                      #   `https://h/a/b` never matches); `file://` is
                                      #   the one scheme that IS a local path.
    r"/(?!/)"                         # a single leading separator, never a URL's '//'
    r"(?!Users/|home/|root/)"         # category 4 owns these -- never double-redact,
                                      #   never swallow the readable tail it preserved
    r"(?!<)"                          # not an already-placeheld '/<...'
    rf"{_PATH_SEGMENT}(?:/{_PATH_SEGMENT})*"   # >= 1 segment -- NO floor (D3-001)
)

# The one literal category 5 and C.7's field-level rule both substitute. It borrows
# NOTHING from the input -- not the basename, not the first segment, not a length hint,
# not a hash -- because every candidate fragment is itself environment-identifying in
# some real layout, and "keep the safe part" would be the allowlist mistake again.
FOREIGN_PATH_PLACEHOLDER = "<REDACTED:foreign_absolute_path>"

REDACTION_CATEGORIES = (
    (
        "orca_dispatch_capability",
        re.compile(r"\bdcap_[A-Za-z0-9_\-]{8,}"),
        "<REDACTED:orca_dispatch_capability>",
    ),
    (
        "url_credential",
        re.compile(r"\b([A-Za-z][A-Za-z0-9+.\-]*)://[^\s/@:]+:[^\s/@]+@"),
        r"\1://<REDACTED:url_credential>@",
    ),
    (
        "env_secret_pattern",
        re.compile(
            r"(?i)\b([A-Z0-9_]*(?:SECRET|TOKEN|PASSWORD|PASSWD|API_?KEY|PRIVATE_KEY"
            r"|ACCESS_KEY)[A-Z0-9_]*)\s*([=:])\s*(\"[^\"\n]*\"|'[^'\n]*'|[^\s\n]+)"
        ),
        r"\1\2<REDACTED:env_secret_pattern>",
    ),
    (
        # Only the user-name segment is replaced: the /Users/ prefix and everything
        # after the segment survive, so the path stays semantically readable while
        # the identifying part is gone. The (?!<|\{) lookahead is the same one
        # validate_skills.py uses, so an already-placeheld /Users/<name>/ is not
        # double-redacted. Windows C:\Users\<name> is deliberately NOT in v1.1:
        # COMPATIBILITY.md claims no Windows support for the runtime path, and an
        # untested pattern is worse than a stated gap. It is a MINOR-bump candidate.
        "absolute_local_path",
        _HOME_ABSOLUTE_PATH,
        r"\1<REDACTED:absolute_local_path>",
    ),
    (
        # Everything else absolute, replaced WHOLE. Readability is preserved only
        # where it is provably safe -- the three home spellings above and
        # repo-relative paths, which have no leading '/' and are never touched --
        # and surrendered everywhere else. What is lost is the environment-specific
        # spelling of a location; WHICH artifact is meant stays recoverable from the
        # retained artifact_path and the *_digest_pre_redaction next to it.
        "foreign_absolute_path",
        _FOREIGN_ABSOLUTE_PATH,
        FOREIGN_PATH_PLACEHOLDER,
    ),
)


def redact_text(
    text: str, *, policy_version: str = FINAL_REVIEW_REDACTION_POLICY_VERSION
) -> tuple[str, tuple[dict[str, int], ...]]:
    """Deterministic. A pure function of (text, policy_version).

    No randomness, no salt, no clock, no environment, no filesystem, no
    path-dependent state: the same input under the same policy produces byte-identical
    output and an identical `redactions` list on any machine, in any process, at any
    time. That determinism is what makes "redaction 전후 identity 검증 가능" a testable
    property when the raw bytes are deliberately never retained -- re-running the
    pipeline on the same source reproduces both digests and the same counts.

    An unknown policy_version raises rather than silently falling back: a digest is
    only comparable against a digest produced by the SAME policy.

    The returned list carries an entry only for a category that matched at least
    once, in policy order, so `[]` unambiguously means "nothing was substituted".
    It carries NO offsets and NO per-occurrence digest: offsets plus the retained
    text localize the removed value and reveal its length, which is a leak channel
    the category+count form does not have. Adding either later is an additive MINOR
    bump.
    """
    if policy_version != FINAL_REVIEW_REDACTION_POLICY_VERSION:
        raise RunLoggingError(
            f"unknown redaction policy version {policy_version!r}; expected "
            f"{FINAL_REVIEW_REDACTION_POLICY_VERSION!r} -- a digest produced under an "
            "unknown policy is not comparable to anything"
        )
    out = text
    counts: list[dict[str, int]] = []
    for name, pattern, replacement in REDACTION_CATEGORIES:
        out, hits = pattern.subn(replacement, out)
        if hits:
            counts.append({"category": name, "count": hits})
    return out, tuple(counts)


# ---- D-H: the one gate every string embedded in the evidence bundle passes --------
# The rule, stated once, and it is the exporter's whole posture:
#
#   No text enters FINAL_REVIEW_EVIDENCE_BUNDLE.json that has not been proved
#   residue-free under the current redaction policy. Text that cannot be made
#   residue-free is OMITTED with a stated reason and a digest -- never embedded,
#   and never silently truncated.
#
# Three consequences, all load-bearing:
#   1. the authoritative local ORCHESTRATOR_LOG.md is opened read-only and is never
#      rewritten; only the exported COPY is sanitized;
#   2. sanitization is redact_text() itself, not a second policy -- a second copy of a
#      redaction policy is precisely the drift R1 punished;
#   3. residue is a hard stop for the affected VALUE, not for the export: the bundle is
#      still written, still lists every attempt, and says which content it withheld and
#      why. Reporting beats denying, exactly as the digest-mismatch path already does.

# Closed vocabulary, the same discipline REDACTION_CATEGORIES and
# FINAL_REVIEW_RETAINED_PATH_FIELDS already use: a reason absent from this tuple is not
# a reason, and that is visible here rather than inferred from an assembly expression.
EMBED_OMISSION_REASONS = (
    "redaction_residue",
    "table_structure_changed",
    "unreadable",
)


def _residual_matches_are_self_output(text: str) -> bool:
    """D-H.2 step 2. True when the policy has nothing left to REMOVE from `text`.

    Not `redact_text(text)[0] == text`, and not `redact_text(text)[1] == ()`: the first
    is a whole-string proxy for a per-match property -- a match that removed something
    can be masked by matches elsewhere in the text -- and the second is a DIFFERENT
    property that redaction/1.1 cannot satisfy on the very inputs this gate exists for,
    because `env_secret_pattern` and `url_credential` preserve a readable anchor on
    purpose and therefore re-match their own placeholder output while rewriting it to
    identical bytes.
    """
    return all(
        match.expand(replacement) == match.group(0)
        for _name, pattern, replacement in REDACTION_CATEGORIES
        for match in pattern.finditer(text)
    )


def safe_embedded_text(
    raw: str, *, redact: bool
) -> tuple[str | None, tuple[dict[str, int], ...], str]:
    """Return `(text_or_None, redactions, omission_reason)`.

    `redact=True`  -- the source is NOT already a post-redaction artifact
                      (ORCHESTRATOR_LOG.md). Apply redact_text() first.
    `redact=False` -- the source IS a digest-bound post-redaction artifact
                      (input.md / report.md). Re-redacting would break the recorded
                      digest identity, so this path VERIFIES ONLY.

    The residue check is a fixed point of the policy, and that is a CLOSED statement
    over the policy's own categories rather than an inspection: category 5
    (`foreign_absolute_path`) matches every absolute POSIX path with no minimum segment
    count and replaces it whole, and category 4 owns the three home spellings, so a
    fixed point means no absolute path, no `dcap_...`, no `scheme://user:pass@` and no
    SECRET/TOKEN/PASSWORD/API_KEY-named assignment survived.

    The fixed point is decided PER MATCH, by `_residual_matches_are_self_output()`:
    every residual match of every category must expand to exactly its own span. The
    second pass may still RECOGNISE text; it must have nothing left to REMOVE. Text
    equality (`again == candidate`) is an immediate consequence -- a substitution whose
    every replacement equals its own span cannot change the string -- so it is not
    asserted separately. It is not asserted as a proxy either: comparing two whole
    strings lets a match that removed something be masked by matches elsewhere in the
    text, and the per-match rule cannot be masked that way.

    It is deliberately NOT additionally asserted that the second pass reports no
    category at all. That is a DIFFERENT property, not a stricter one, and this policy
    cannot satisfy it on exactly the inputs this gate exists for: every category
    preserves a readable anchor on purpose -- `env_secret_pattern` keeps `KEY=` and its
    value class `[^\s\n]+` re-matches its own `<REDACTED:env_secret_pattern>` output,
    and `url_credential` keeps `scheme://...@` and re-matches likewise. Both rewrite to
    identical bytes, so both are counted on a second pass while removing nothing.
    Requiring a zero count would omit the log from every bundle that logged a
    secret-named assignment or a credentialed URL -- i.e. exactly the bundles the
    sanitization exists for.

    The structure check exists so that a FUTURE policy which introduced a newline or a
    `|` into a placeholder fails loudly here instead of silently corrupting the
    exported log table. It is applied only on the `redact=True` path, because that is
    the only path that transforms anything.
    """
    if redact:
        candidate, redactions = redact_text(raw)
    else:
        candidate, redactions = raw, ()
    if not _residual_matches_are_self_output(candidate):
        return None, redactions, "redaction_residue"
    if redact:
        if candidate.count("\n") != raw.count("\n"):
            return None, redactions, "table_structure_changed"
        for before, after in zip(raw.splitlines(), candidate.splitlines()):
            if before.count("|") != after.count("|"):
                return None, redactions, "table_structure_changed"
    return candidate, redactions, ""


# ---- P-PATH: the safety property EVERY retained path-bearing field must satisfy ----
# The pipeline above is capture -> redact_text() -> write. A retained artifact can also
# carry a filesystem path in a field that never goes through it: report.contract_path is
# the concrete case, and that is exactly how a raw scratch path reached a shipped
# record.json while the record truthfully reported "redactions": []. So the policy is
# stated once more, as a FIELD-LEVEL property that holds regardless of which code path
# wrote the value:
#
#   Every string field of a retained artifact that can hold a filesystem path lands, on
#   disk, in exactly one of four output categories --
#     P1 <ARTIFACT_ROOT>-relative        P2 "<REPO>/"-prefixed repository-relative
#     P3 not a filesystem path at all    P4 the FOREIGN_PATH_PLACEHOLDER literal, whole
#   -- and there is no fifth category, no segment-count condition, and no "the policy
#   left it unchanged" case.
#
# The last exclusion is the point. A postcondition phrased as "redaction is a fixed
# point of this value" is CIRCULAR: a value the policy does not recognise satisfies it
# trivially, so a raw one-segment "/luminous" would have passed it (D3-001). Asking
# which of four ALLOWED categories the value is in has no "unrecognised" answer to give,
# so a shape nobody anticipated fails closed.

# A plain relative POSIX path: at least one character, no leading '/', no '..' segment,
# no whitespace, no angle bracket (so a placeholder can never masquerade as P1/P2), no
# backslash and no drive letter (so a Windows path is never mistaken for a relative
# one), and no '://' anywhere (so a URL -- 'file://...' in particular -- is decided by
# the URL test and can never fall through to here as a "relative path").
_SAFE_RELATIVE_PATH = re.compile(r"(?!/)(?![A-Za-z]:)(?!(?:.*/)?\.\.(?:/|$))(?!.*://)[^\s<>\\]+")

# A URL that is not a local file: any scheme except 'file', and no whitespace.
_NON_FILE_URL = re.compile(r"(?!(?i:file):)[A-Za-z][A-Za-z0-9+.\-]*://\S*")

REPO_RELATIVE_PREFIX = "<REPO>/"

# The closed list of retained record fields P-PATH governs. A new field that can hold a
# path must be added here in the same commit that adds it -- the same discipline
# FINAL_REVIEW_REDACTED_METADATA_FIELDS already uses, and for the same reason: a field
# absent from the list is not covered, and that must be visible here rather than
# inferred from an assembly expression.
FINAL_REVIEW_RETAINED_PATH_FIELDS = (
    "stored_task_spec.artifact_path",
    "report.artifact_path",
    "report.contract_path",
)


def normalize_retained_path_field(value: str) -> str:
    """Total: every input maps into exactly one of P1..P4. Never calls redact_text().

    The four categories are mutually exclusive by construction -- the P4 literal and a
    URL both carry characters _SAFE_RELATIVE_PATH forbids -- so no test order can change
    the answer; the order below only reads most directly.
    """
    if not isinstance(value, str):
        return FOREIGN_PATH_PLACEHOLDER
    if value == "" or value == FOREIGN_PATH_PLACEHOLDER:      # P3 (empty) / P4
        return value
    if _NON_FILE_URL.fullmatch(value):                        # P3
        return value
    if value.startswith(REPO_RELATIVE_PREFIX) and _SAFE_RELATIVE_PATH.fullmatch(
        value[len(REPO_RELATIVE_PREFIX) :]
    ):
        return value                                          # P2
    if _SAFE_RELATIVE_PATH.fullmatch(value):                  # P1
        return value
    return FOREIGN_PATH_PLACEHOLDER                           # everything else, WHOLE


def assert_retained_path_field(value: str) -> None:
    """Fail-closed postcondition. Raises rather than write a value outside P1..P4.

    It is deliberately NOT a fixed-point test: re-running the total classifier asks the
    only question that matters -- which allowed category is this value in? -- and a
    value the free-text policy happens not to match has no way to sneak through.
    """
    if normalize_retained_path_field(value) != value:
        raise RunLoggingError(
            f"P-PATH violation in a retained path field: {value!r} is in none of the "
            "four allowed output categories (<ARTIFACT_ROOT>-relative, <REPO>/-relative, "
            f"not-a-path, or the whole-value {FOREIGN_PATH_PLACEHOLDER})"
        )


def _assert_retained_path_fields(record: dict) -> None:
    """The closed table above, checked at record assembly, before anything is staged."""
    for dotted in FINAL_REVIEW_RETAINED_PATH_FIELDS:
        section, _, field = dotted.partition(".")
        container = record.get(section)
        if not isinstance(container, dict) or field not in container:
            continue
        assert_retained_path_field(container[field])


# ---- capture: post-dispatch reads, and nothing else -------------------------------
# This module cannot import from scripts/ (see the module docstring), so it resolves
# the CLI command the same way it already re-implements _ensure_run_artifact_root():
# the same ORCA_CLI_COMMAND environment variable orca_runtime_harness.py reads.
#
# Captured text arrives on the subprocess's stdout PIPE -- never through a file, never
# through an argument, never through an environment variable -- is parsed in memory,
# redacted in memory, and only the redacted form is written. That deletes the leak
# class rather than mitigating it.


def _orca_command() -> str:
    return os.environ.get("ORCA_CLI_COMMAND", "orca")


def _run_orca_json(args: tuple[str, ...]) -> tuple[Any, str]:
    """`(payload, error)`. Never raises: every failure funnels into `error`.

    A record that says "the input could not be captured, and here is exactly why"
    is evidence. A missing record is not.
    """
    try:
        completed = subprocess.run(
            [_orca_command(), *args],
            capture_output=True,
            text=True,
            timeout=CAPTURE_TIMEOUT_SECONDS,
            check=False,
        )
    except FileNotFoundError:
        return None, f"{_orca_command()!r} was not found on PATH"
    except subprocess.TimeoutExpired:
        return None, f"timed out after {CAPTURE_TIMEOUT_SECONDS}s"
    except OSError as error:
        return None, f"could not run the capture command: {error}"
    if completed.returncode != 0:
        stderr = (completed.stderr or "").strip().replace("\n", " ")[:400]
        return None, f"exit {completed.returncode}: {stderr}"
    try:
        return json.loads(completed.stdout), ""
    except (json.JSONDecodeError, TypeError) as error:
        return None, f"unparseable JSON on stdout: {error}"


def _unwrap(payload: Any, key: str) -> Any:
    """Read `key` out of a payload that may or may not be wrapped in `result`."""
    if isinstance(payload, dict):
        if key in payload:
            return payload[key]
        result = payload.get("result")
        if isinstance(result, dict) and key in result:
            return result[key]
    return None


def capture_stored_task_spec(run_id: str, task_id: str) -> tuple[str | None, str]:
    """The spec Orca STORED for this Task, read back after the dispatch.

    Returns `(spec, "")` or `(None, reason)`. This is deliberately the stored spec
    and not the delivered bytes -- Orca exposes no read-back of what the terminal
    received -- and the record says so in a field of its own rather than only in
    prose, so no reader can mistake one for the other.
    """
    payload, error = _run_orca_json(
        ("orchestration", "task-list", "--run", run_id, "--json")
    )
    if payload is None:
        return None, error
    tasks = _unwrap(payload, "tasks")
    if tasks is None and isinstance(payload, list):
        tasks = payload
    if not isinstance(tasks, list):
        return None, "no task list in the capture response"
    for task in tasks:
        if isinstance(task, dict) and task.get("id") == task_id:
            spec = task.get("spec")
            if not isinstance(spec, str):
                return None, f"task {task_id} carries no spec string"
            return spec, ""
    return None, f"task {task_id} is not in run {run_id}'s task list"


def capture_delivery_evidence(task_id: str) -> tuple[dict | None, str]:
    """The dispatch record for this Task: delivery evidence, separate from the spec.

    `preamble` is never read. It is re-rendered against reader state and has been
    observed naming the wrong coordinator handle and omitting capability material
    entirely, so it is not evidence of what was delivered.
    """
    payload, error = _run_orca_json(
        ("orchestration", "dispatch-show", "--task", task_id, "--json")
    )
    if payload is None:
        return None, error
    dispatch = _unwrap(payload, "dispatch")
    if not isinstance(dispatch, dict):
        return None, "no dispatch object in the capture response"
    return dispatch, ""


def _capture_repository_state() -> dict | None:
    """`{head_commit, branch, dirty}` or None when git is unavailable."""

    def _git(*args: str) -> str | None:
        try:
            completed = subprocess.run(
                ["git", *args],
                capture_output=True,
                text=True,
                timeout=CAPTURE_TIMEOUT_SECONDS,
                check=False,
            )
        except (FileNotFoundError, OSError, subprocess.TimeoutExpired):
            return None
        if completed.returncode != 0:
            return None
        return completed.stdout.rstrip("\n")

    head = _git("rev-parse", "HEAD")
    if head is None:
        return None
    status = _git("status", "--porcelain")
    return {
        "head_commit": head,
        "branch": _git("rev-parse", "--abbrev-ref", "HEAD") or "",
        "dirty": bool(status),
    }


# ---- report resolution and parsing ------------------------------------------------


def final_review_report_ladder_path(
    run_id: str, attempt: int, *, base: Path | None = None
) -> Path:
    """Section 9's ladder: attempt 1 unsuffixed, attempt N>=2 _iteration<N>."""
    attempt = assert_attempt_in_domain(attempt, label="final_review_attempt")
    suffix = "" if attempt == 1 else f"_iteration{attempt}"
    return _ensure_run_artifact_root(run_id, base=base) / f"FINAL_REVIEW{suffix}.md"


def resolve_final_review_report(
    run_id: str,
    attempt: int,
    *,
    base: Path | None = None,
    report_path: str | Path | None = None,
) -> tuple[Path, str]:
    """`(path, resolution)` -- which of REPORT_RESOLUTIONS produced it."""
    if report_path:
        return Path(report_path), "explicit"
    laddered = final_review_report_ladder_path(run_id, attempt, base=base)
    if laddered.exists():
        return laddered, "ladder"
    unsuffixed = final_review_report_ladder_path(run_id, 1, base=base)
    if attempt > 1 and unsuffixed.exists():
        return unsuffixed, "fallback_unsuffixed"
    return laddered, "ladder"


_RESULT_LINE = re.compile(r"^RESULT:\s*(.+?)\s*$", re.MULTILINE)
_REVIEW_VERDICT_LINE = re.compile(r"^REVIEW_VERDICT:\s*(.+?)\s*$", re.MULTILINE)
_FINDING_ID_LINE = re.compile(r"^ID:\s*(\S+)\s*$", re.MULTILINE)
_BLOCKING_LINE = re.compile(r"^Blocking:\s*(YES|NO)\s*$", re.MULTILINE)
RESULT_VALUES = ("PASS", "FAIL")
REVIEW_VERDICT_VALUES = ("PASS", "PASS WITH NOTES", "FAIL", "BLOCKED")

# I-002-R1. A capture that fails its enum check is report-controlled FREE TEXT, and
# `record.json` is a retained artifact. So the invalid capture never becomes the
# field's value: `result` and `review_verdict` hold their enum, `""`, or this
# sentinel and nothing else, which is what makes them safe to persist unredacted.
# The offending bytes are said once, in `parse_error` -- the field this codebase
# already uses to say what was wrong -- and that field goes through the same
# redaction policy every other free-form metadata field does.
PARSED_ENUM_INVALID = "INVALID"

# A finding id is an identifier, not prose. Anything not shaped like one is replaced
# rather than retained (which also keeps the two lists' lengths honest), and what IS
# retained is still report-controlled, so it is redacted on top of the shape check.
PARSED_FINDING_ID_INVALID = "INVALID_ID"
_SAFE_FINDING_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$")


def _finding_id(captured: str) -> str:
    """The captured id if it is ID-shaped, the sentinel otherwise."""
    return captured if _SAFE_FINDING_ID.match(captured) else PARSED_FINDING_ID_INVALID


def parse_final_review_report(text: str) -> dict:
    """The section 11/17 shape, copied VERBATIM -- never re-derived, never collapsed.

    `RESULT:` stays two-valued and `REVIEW_VERDICT:` stays four-valued: a VALID
    value is carried through exactly as the report wrote it, so nothing here can
    turn a `PASS WITH NOTES` into a `PASS` or a `BLOCKED` into a `FAIL`.

    An INVALID value is not carried through: it becomes `PARSED_ENUM_INVALID` and
    the raw capture is quoted only into `parse_error`. Verbatim is a fidelity rule
    about the contract's enums, not a licence to copy arbitrary report text into a
    retained record (I-002-R1).
    """
    parsed: dict[str, Any] = {
        "parse_status": "ok",
        "parse_error": "",
        "result": "",
        "review_verdict": "",
        "blocking_finding_ids": [],
        "non_blocking_finding_ids": [],
    }
    result = _RESULT_LINE.search(text)
    if result is None:
        parsed["parse_status"] = "malformed"
        parsed["parse_error"] = "no RESULT: line"
        return parsed
    captured_result = result.group(1)
    if captured_result not in RESULT_VALUES:
        parsed["result"] = PARSED_ENUM_INVALID
        parsed["parse_status"] = "malformed"
        parsed["parse_error"] = (
            f"RESULT: {captured_result!r} is not one of {RESULT_VALUES}"
        )
        return parsed
    parsed["result"] = captured_result
    verdict = _REVIEW_VERDICT_LINE.search(text)
    if verdict is not None:
        captured_verdict = verdict.group(1)
        if captured_verdict not in REVIEW_VERDICT_VALUES:
            parsed["review_verdict"] = PARSED_ENUM_INVALID
            parsed["parse_status"] = "malformed"
            parsed["parse_error"] = (
                f"REVIEW_VERDICT: {captured_verdict!r} is not one of "
                f"{REVIEW_VERDICT_VALUES}"
            )
            return parsed
        parsed["review_verdict"] = captured_verdict
    blocking: list[str] = []
    non_blocking: list[str] = []
    matches = list(_FINDING_ID_LINE.finditer(text))
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
        block = text[match.end():end]
        flag = _BLOCKING_LINE.search(block)
        if flag is not None and flag.group(1) == "YES":
            blocking.append(_finding_id(match.group(1)))
        elif flag is not None:
            non_blocking.append(_finding_id(match.group(1)))
    parsed["blocking_finding_ids"] = blocking
    parsed["non_blocking_finding_ids"] = non_blocking
    return parsed


# ---- the provenance ladder, as one shared first-match evaluation ------------------
# D-B B.2. Both emission points (the live Orca runtime and the deterministic e2e
# harness) evaluate it here rather than each implementing the table, because a
# provenance assignment that two code paths could disagree about is not reproducible
# -- which is the whole property the ladder exists to give.


def probe_final_review_report(
    run_id: str,
    attempt: int,
    *,
    base: Path | None = None,
    report_path: str | Path | None = None,
) -> tuple[str, str]:
    """`(capture_status, parse_status)` for the report, writing nothing.

    The ladder's rows 4 and 5 are about the report, so a caller has to be able to
    ask about it before it decides what to record.
    """
    path, _resolution = resolve_final_review_report(
        run_id, attempt, base=base, report_path=report_path
    )
    if not path.exists():
        return "absent", "not_attempted"
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return "unreadable", "not_attempted"
    return "captured", parse_final_review_report(text)["parse_status"]


def resolve_final_review_provenance(
    *,
    determinable: bool = True,
    input_rejected: bool = False,
    capability_invalid: bool = False,
    settled: bool = False,
    report_capture_status: str = "absent",
    report_parse_status: str = "not_attempted",
    superseded_by_retry: bool = False,
) -> tuple[str, str, str]:
    """`(provenance_state, void_reason, settlement_state)`, first match wins.

    The ladder is evaluated at the single write point, at settlement, which is what
    makes immutability and provenance compatible: every row is determinable then, so
    a record is complete when it is written and never needs editing. Row 7 is not a
    retroactive blessing -- the Coordinator acts on a cleanly settled dispatch's
    verdict immediately, so "will this one be acted on?" is known at that moment, and
    row 6 covers the only case where a settled dispatch is knowingly not acted on.

    `determinable=False` is row 8: the caller could not tell which of 1-7 applies, and
    says so rather than guessing. It reads `unknown`, never `accepted`.
    """
    if not determinable:
        return PROVENANCE_UNKNOWN, "", "unknown"
    if input_rejected:
        return PROVENANCE_VOIDED, "dispatch_input_rejected", "not_settled"
    if capability_invalid:
        return PROVENANCE_VOIDED, "dispatch_capability_invalid", "not_settled"
    if not settled:
        return PROVENANCE_VOIDED, "settlement_failure", "not_settled"
    if report_capture_status != "captured":
        return PROVENANCE_VOIDED, "report_missing", "settled"
    if report_parse_status == "malformed":
        return PROVENANCE_VOIDED, "report_malformed", "settled"
    if superseded_by_retry:
        return PROVENANCE_VOIDED, "superseded_by_retry", "settled"
    return PROVENANCE_ACCEPTED, "", "settled"


